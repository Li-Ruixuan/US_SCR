"""
rerun_plan.md, Tier 1, block B4: write a shell script with the missing ORB-SLAM3 runs.

For every target (new folder <- existing template folder, mode) the script does three steps, taking every
argument from the template's slam_eval.json (sequence, session root, scan runs, sweeps, camera calibration):
  1. rgbd_online on the template's exported sequence (same seq/, camera.yaml, associations.txt);
     N_MAP = rows of seq/index.csv whose run starts with "room-" (the room scan comes first);
  2. slam_baseline.py evaluate --smooth 2 on the new online.txt;
  3. us_analysis.py shape on the new poses.
A target whose folder already exists is skipped (rule 6: nothing is overwritten). Each run is checked for
completeness: times.txt must have one line per frame of associations.txt. A run that stops early (ORB-SLAM3
crash) is reported as INCOMPLETE and is not evaluated; per rule 3 it is not silently repeated.

  python tools/paper/make_b4.py > runs/paper_final/b4_orbslam.sh
  bash runs/paper_final/b4_orbslam.sh 2>&1 | tee runs/paper_final/b4_orbslam.log

The runs play the sequence in real time (rgbd_online waits for each timestamp), so run them one after the
other, not in parallel: parallel runs would compete for the CPU and change ORB-SLAM3's behaviour.
"""

import argparse
import csv
import json
import shlex
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RUNS = REPO / "runs"

MAIN = ["3XX", "4XXA", "4XXB", "4XXC", "4XXD", "4XXE",
        "5XXA-exam", "5XXB-exam", "5XXC-exam", "5XXD-exam", "5XXE-exam"]
OCC = ["5XXB-exam-occ30", "5XXB-exam-occ60", "5XXC-exam-occ30", "5XXC-exam-occ60"]
MODE = {"loc": "localize", "reloc": "reloc"}


def targets():
    """(new folder, template folder, rgbd_online mode)."""
    t = []
    # Order = priority, so that a stopped script still has the runs the paper needs most.
    # B4a: replacements for the three trajectories that stop before the end of the sequence (ORB-SLAM3
    # stopped; found by comparing end times with the other modes of the same split, 2026-11-20):
    # P-rearr2 60 % loc ends at 268 s and reloc at 261 s of 579 s; P-rearr1 60 % reloc ends at 504 s of 549 s.
    t.append(("slam-5XXC-exam-occ60-loc-r4", "slam-5XXC-exam-occ60-loc", "loc"))
    t.append(("slam-5XXC-exam-occ60-reloc-r2", "slam-5XXC-exam-occ60-reloc", "reloc"))
    t.append(("slam-5XXB-exam-occ60-reloc-r2", "slam-5XXB-exam-occ60-reloc", "reloc"))
    for s in OCC:                                    # B4b: loc repeats on the occluded settings
        for r in ("r2", "r3"):
            t.append((f"slam-{s}-loc-{r}", f"slam-{s}-loc", "loc"))
    for s in MAIN:                                   # B4c (optional): reloc repeats on the 11 main splits
        for r in ("r2", "r3"):
            t.append((f"slam-{s}-reloc-{r}", f"slam-{s}-reloc", "reloc"))
    return t


def n_map(seq):
    rows = list(csv.reader(open(seq / "index.csv")))[1:]
    n = 0
    for _, name, _ in rows:
        if not name.startswith("room-"):
            break
        n += 1
    if n == 0 or any(r[1].startswith("room-") for r in rows[n:]):
        raise SystemExit(f"{seq}/index.csv: room-scan rows are not all at the start")
    return n


def q(x):
    return shlex.quote(str(x))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--orb", default="/data2/u0137815/ORB_SLAM3", help="ORB-SLAM3 checkout with the Tracking.cc patch")
    ap.add_argument("--py", default="/data2/u0137815/conda/envs/usrgbd/bin/python")
    ap.add_argument("--extra", nargs="*", default=[],
                    help="more targets as NEW=TEMPLATE (mode taken from the template's name), e.g. from check 2")
    ap.add_argument("--first", type=int, default=0,
                    help="keep only the first N targets of the priority list (11 = replacements + occluded repeats)")
    args = ap.parse_args()
    orb = Path(args.orb)
    exe, voc = orb / "Examples/RGB-D/rgbd_online", orb / "Vocabulary/ORBvoc.txt"

    tg = targets()
    for e in args.extra:
        new, tpl = e.split("=")
        tg.append((new, tpl, "reloc" if tpl.endswith("-reloc") else "loc"))
    if args.first:
        tg = tg[:args.first]

    out = ["#!/bin/bash", f"# generated by tools/paper/make_b4.py: {len(tg)} ORB-SLAM3 runs, one after the other",
           f"PY={q(args.py)}", f"cd {q(REPO)}",
           f"[ -x {q(exe)} ] || {{ echo 'missing {exe}'; exit 1; }}",
           f"[ -f {q(voc)} ] || {{ echo 'missing {voc}'; exit 1; }}",
           "(cd " + q(orb) + " && git diff --quiet src/Tracking.cc) && { echo 'Tracking.cc patch missing'; exit 1; }",
           "done_ok=0; done_bad=0; skipped=0", ""]
    for new, tpl, mode in tg:
        f = RUNS / tpl / "slam_eval.json"
        if not f.exists():
            out.append(f"echo 'SKIP {new}: template {tpl} has no slam_eval.json'; skipped=$((skipped+1))")
            continue
        a = json.load(open(f))["args"]
        seq = REPO / a["seq"]
        nm = n_map(seq)
        nframes = sum(1 for line in open(seq / "associations.txt") if line.strip() and not line.startswith("#"))
        d = f"runs/{new}"
        ev = [f"tools/slam_baseline.py", "evaluate", "--root", a["root"], "--scan-runs", *a["scan_runs"]]
        if a.get("runs"):
            ev += ["--runs", *a["runs"]]
        ev += ["--seq", a["seq"], "--traj", f"{d}/online.txt"]
        if a.get("cam_calib_from"):
            ev += ["--cam-calib-from", a["cam_calib_from"]]
        if a.get("no_cam_calib"):
            ev += ["--no-cam-calib"]
        ev += ["--smooth", "2", "--source", a["source"], "--calib", a["calib"], "--hand-eye", a["hand_eye"], "--out", d]
        out += [
            f"# {new} <- {tpl} (mode {MODE[mode]}, N_MAP {nm}, {nframes} frames)",
            f"if [ -e {q(d)} ]; then echo 'SKIP {new}: exists'; skipped=$((skipped+1)); else",
            f"  mkdir -p {q(d)}",
            f"  echo \"$(date '+%F %T') START {new}\"",
            f"  {q(exe)} {q(voc)} {q(seq / 'camera.yaml')} {q(seq)} {q(seq / 'associations.txt')} {q(d)} "
            f"{MODE[mode]} {nm} > {q(d + '/orbslam.log')} 2>&1",
            f"  rc=$?; n=$(wc -l < {q(d + '/times.txt')} 2>/dev/null || echo 0)",
            f"  if [ \"$n\" -ne {nframes} ]; then",
            f"    echo \"INCOMPLETE {new}: exit $rc, $n / {nframes} frames (see {d}/orbslam.log)\"; done_bad=$((done_bad+1))",
            "  else",
            f"    echo \"COMPLETE {new}: exit $rc\"",
            "    $PY " + " ".join(q(x) for x in ev) + f" > {q(d + '/evaluate.log')} 2>&1 || echo 'EVALUATE FAILED {new}'",
            f"    $PY tools/us_analysis.py shape --json {d}/poses/*.json --out {q(d + '/shape.md')} "
            f"> {q(d + '/shape.log')} 2>&1 || echo 'SHAPE FAILED {new}'",
            "    done_ok=$((done_ok+1))",
            "  fi",
            "fi", ""]
    out.append('echo "complete $done_ok, incomplete $done_bad, skipped $skipped"')
    print("\n".join(out))


if __name__ == "__main__":
    main()
